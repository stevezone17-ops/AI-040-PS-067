"""Integration test fixtures, builder DSL, and independent constraint verifier.

Provides deterministic synthetic dataset generators for:
  - Scenario A: Small examination problem (10 courses, 50 students, 5 dates, FN/AN)
  - Scenario B: Medium examination problem (30 courses, 300 students, 10 dates)
  - Scenario C: Large examination problem (100 courses, 1000 students, 15 dates)
  - Scenario D: Deliberately infeasible problem (resource shortages, unpairable small courses)
and an independent dual-oracle constraint validator asserting hard and soft invariants
directly on raw student/course data without invoking internal scheduling functions.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from datetime import date, timedelta
from enum import Enum
from typing import Any

# ---------------------------------------------------------------------------
# Test-only Integration Domain Stubs
# ---------------------------------------------------------------------------


class SessionSlot(Enum):
    """Session slot enumeration (FN/AN)."""

    FN = "FN"
    AN = "AN"


@dataclass(frozen=True)
class IntegrationCourse:
    """Course entity for integration tests."""

    course_code: str
    credits: int = 3
    department: str = "CSE"
    duration_hours: int = 3
    is_supplementary: bool = False
    semester: int = 1
    name: str = ""


@dataclass(frozen=True)
class IntegrationStudent:
    """Student entity for integration tests."""

    register_number: str
    programme: str = "BTech-CSE"
    semester: int = 1
    backlog_consent: bool = False


@dataclass(frozen=True)
class IntegrationEnrolment:
    """Enrolment entity linking student to course."""

    register_number: str
    course_code: str
    is_backlog: bool = False


@dataclass(frozen=True)
class IntegrationHall:
    """Hall entity for integration tests."""

    hall_id: str
    capacity: int = 100
    floor: int = 0
    rows: int = 10
    columns: int = 10


@dataclass(frozen=True)
class IntegrationExamSession:
    """Examination session entity for integration tests."""

    session_id: str
    session_index: int
    exam_date: date
    slot: SessionSlot
    is_supplementary_window_date: bool = False


@dataclass(frozen=True, slots=True)
class IntegrationTimeInterval:
    """Test-only stub for TimeInterval value object."""

    start_minutes: int
    end_minutes: int


@dataclass(frozen=True, slots=True)
class IntegrationExamWindow:
    """Test-only stub for ExamWindow entity."""

    start_date: date
    end_date: date
    holidays: frozenset[date] = field(default_factory=frozenset)
    closed_slots: frozenset[tuple[date, SessionSlot]] = field(
        default_factory=frozenset
    )
    window_id: str = "MAIN_WINDOW"


@dataclass(frozen=True, slots=True)
class IntegrationGeneratedSession:
    """Full session entity generated by ALG-02."""

    session_id: str
    session_index: int
    exam_date: date
    slot: SessionSlot
    base_window: IntegrationTimeInterval
    is_supplementary_window_date: bool
    iso_week_key: tuple[int, int]


@dataclass
class IntegrationRegistry:
    """Problem registry container for integration tests."""

    courses: dict[str, IntegrationCourse] = field(default_factory=dict)
    students: dict[str, IntegrationStudent] = field(default_factory=dict)
    sessions: tuple[IntegrationExamSession, ...] = ()
    halls: dict[str, IntegrationHall] = field(default_factory=dict)
    enrolments_by_course: dict[str, list[IntegrationEnrolment]] = field(
        default_factory=dict
    )
    enrolments_by_student: dict[str, list[IntegrationEnrolment]] = field(
        default_factory=dict
    )

    def __post_init__(self) -> None:
        # Cross-populate enrolments if only one side is supplied
        if not self.enrolments_by_course and self.enrolments_by_student:
            by_c: dict[str, list[IntegrationEnrolment]] = {}
            for e_list in self.enrolments_by_student.values():
                for e in e_list:
                    by_c.setdefault(e.course_code, []).append(e)
            self.enrolments_by_course = by_c
        elif not self.enrolments_by_student and self.enrolments_by_course:
            by_s: dict[str, list[IntegrationEnrolment]] = {}
            for e_list in self.enrolments_by_course.values():
                for e in e_list:
                    by_s.setdefault(e.register_number, []).append(e)
            self.enrolments_by_student = by_s

        # Ensure all referenced students exist in self.students
        for s_id in self.enrolments_by_student:
            if s_id not in self.students:
                self.students[s_id] = IntegrationStudent(register_number=s_id)

        self.sessions_by_id = {s.session_id: s for s in self.sessions}


# ---------------------------------------------------------------------------
# Independent Constraint Validator (Dual-Oracle)
# ---------------------------------------------------------------------------


def assert_hard_constraints_satisfied(
    result: Any,
    registry: IntegrationRegistry,
    closed_halls: frozenset[tuple[str, str]] = frozenset(),
) -> None:
    """Independently audit all hard constraints on a generated timetable.

    This function does NOT call any internal scheduling algorithm; it evaluates
    the final `assignments` against raw registry data from first principles.

    Verifies:
      1. No same-session student clashes (BR-01, CN-07).
      2. No same-day student clashes without backlog consent (BR-01, CN-08).
      3. Total students in session do not exceed 90% seat capacity ceiling (BR-04, CN-11).
      4. Supplementary window and slot constraints (BR-12, CN-28, EC-08).
      5. No duplicate examination assignments (every course appears at most once).
      6. Total accounted courses == scheduled + unplaced.
    """
    assignments = result.assignments
    sessions_by_id = registry.sessions_by_id

    # 1. Check duplicate course assignments
    assigned_codes = list(assignments.keys())
    assert len(assigned_codes) == len(set(assigned_codes)), (
        f"Duplicate course assignments detected: {assigned_codes}"
    )

    # 2. Build session-to-courses index
    courses_by_session: dict[str, list[str]] = {}
    for code, assign in assignments.items():
        sess_id = assign.session_id
        assert sess_id in sessions_by_id, f"Invalid session ID: {sess_id}"
        courses_by_session.setdefault(sess_id, []).append(code)

    # 3. Same-session clash check (BR-01, CN-07)
    for sess_id, c_codes in courses_by_session.items():
        all_students_in_session: list[str] = []
        for code in c_codes:
            enrs = registry.enrolments_by_course.get(code, [])
            all_students_in_session.extend(e.register_number for e in enrs)

        # Check for duplicated student in same session
        seen_students: set[str] = set()
        for s_id in all_students_in_session:
            assert s_id not in seen_students, (
                f"Same-session student clash in {sess_id}: student {s_id} enrolled in multiple exams!"
            )
            seen_students.add(s_id)

    # 4. Same-day clash check (BR-01, CN-08)
    sessions_by_date: dict[date, list[str]] = {}
    for sess_id in sessions_by_id:
        exam_date = sessions_by_id[sess_id].exam_date
        sessions_by_date.setdefault(exam_date, []).append(sess_id)

    for exam_date, session_ids in sessions_by_date.items():
        if len(session_ids) <= 1:
            continue
        # Compare every pair of sessions on this date
        for i in range(len(session_ids)):
            s1 = session_ids[i]
            c1_list = courses_by_session.get(s1, [])
            for j in range(i + 1, len(session_ids)):
                s2 = session_ids[j]
                c2_list = courses_by_session.get(s2, [])
                for c1 in c1_list:
                    s1_students = {
                        e.register_number
                        for e in registry.enrolments_by_course.get(c1, [])
                    }
                    for c2 in c2_list:
                        s2_students = {
                            e.register_number
                            for e in registry.enrolments_by_course.get(c2, [])
                        }
                        shared = s1_students.intersection(s2_students)
                        for stu_id in shared:
                            stu_obj = registry.students.get(stu_id)
                            has_consent = getattr(
                                stu_obj, "backlog_consent", False
                            )
                            # Must have backlog consent to take 2 exams on the same day (AS-014)
                            assert has_consent, (
                                f"Same-day unconsented clash on {exam_date}: student {stu_id} "
                                f"scheduled in {c1} ({s1}) and {c2} ({s2}) without backlog consent!"
                            )

    # 5. Session capacity check (BR-04, CN-11, AS-001, AS-002)
    for sess_id, c_codes in courses_by_session.items():
        sess_obj = sessions_by_id[sess_id]
        avail_halls = [
            h
            for h in registry.halls.values()
            if (sess_obj.session_id, h.hall_id) not in closed_halls
        ]
        if avail_halls:
            total_cap = sum(h.capacity for h in avail_halls)
            cap_90 = (90 * total_cap) // 100
            total_enrolled = sum(
                len(registry.enrolments_by_course.get(code, []))
                for code in c_codes
            )
            assert total_enrolled <= cap_90, (
                f"Session {sess_id} exceeded 90% seat capacity ceiling: "
                f"{total_enrolled} students > {cap_90} ceiling ({total_cap} total)!"
            )

    # 6. Supplementary examination window and slot check (BR-12, CN-28, EC-08)
    for code, assign in assignments.items():
        course = registry.courses.get(code)
        if course and getattr(course, "is_supplementary", False):
            sess_obj = sessions_by_id[assign.session_id]
            # Must be in supplementary window dates
            assert sess_obj.is_supplementary_window_date, (
                f"Supplementary course {code} scheduled outside supplementary window in {sess_obj.session_id}!"
            )
            enrol_cnt = len(registry.enrolments_by_course.get(code, []))
            slot_val = getattr(sess_obj.slot, "value", sess_obj.slot)
            if enrol_cnt <= 50:
                assert str(slot_val) == "AN", (
                    f"Small supplementary course {code} ({enrol_cnt} students) must be in AN slot; "
                    f"placed in {slot_val} in {sess_obj.session_id}!"
                )


