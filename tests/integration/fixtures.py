# Synthetic Dataset Generators
# ---------------------------------------------------------------------------


def generate_session_sequence(
    start_date: date,
    num_days: int,
    supp_window_days: int = 3,
) -> tuple[IntegrationExamSession, ...]:
    """Generate sequential FN and AN sessions for a given number of days."""
    sessions: list[IntegrationExamSession] = []
    idx = 0
    supp_start_day = max(0, num_days - supp_window_days)

    for day_offset in range(num_days):
        cur_date = start_date + timedelta(days=day_offset)
        is_supp = day_offset >= supp_start_day
        # FN slot
        fn_id = f"{cur_date.isoformat()}_FN"
        sessions.append(
            IntegrationExamSession(
                fn_id, idx, cur_date, SessionSlot.FN, is_supp
            )
        )
        idx += 1
        # AN slot
        an_id = f"{cur_date.isoformat()}_AN"
        sessions.append(
            IntegrationExamSession(
                an_id, idx, cur_date, SessionSlot.AN, is_supp
            )
        )
        idx += 1

    return tuple(sessions)


def build_scenario_a_small(seed: int = 42) -> IntegrationRegistry:
    """Build Scenario A: Small examination problem.

    Scale:
      - 10 courses (CSE, ECE, MECH, CIVIL)
      - 50 students
      - 5 examination dates (10 sessions, FN and AN)
      - Regular and supplementary examinations
      - Shared student enrolments
      - Multiple programmes and semesters
    """
    _ = seed
    sessions = generate_session_sequence(
        date(2025, 12, 1), num_days=5, supp_window_days=2
    )

    halls = {
        "H1": IntegrationHall("H1", capacity=60),
        "H2": IntegrationHall("H2", capacity=40),
    }

    courses = {
        "CSE101": IntegrationCourse(
            "CSE101", 4, "CSE", 3, False, 1, "Intro to Programming"
        ),
        "CSE102": IntegrationCourse(
            "CSE102", 4, "CSE", 3, False, 1, "Data Structures"
        ),
        "ECE101": IntegrationCourse(
            "ECE101", 3, "ECE", 3, False, 1, "Circuit Theory"
        ),
        "ECE102": IntegrationCourse(
            "ECE102", 4, "ECE", 3, False, 2, "Digital Logic"
        ),
        "MEC101": IntegrationCourse(
            "MEC101", 3, "MECH", 3, False, 1, "Engineering Mechanics"
        ),
        "CIV101": IntegrationCourse(
            "CIV101", 3, "CIVIL", 3, False, 1, "Fluid Mechanics"
        ),
        "SUPP_CSE": IntegrationCourse(
            "SUPP_CSE", 3, "CSE", 3, True, 1, "CSE Backlog"
        ),
        "SUPP_ECE": IntegrationCourse(
            "SUPP_ECE", 3, "ECE", 3, True, 2, "ECE Backlog"
        ),
        "SMALL_MEC": IntegrationCourse(
            "SMALL_MEC", 2, "MECH", 3, False, 1, "Workshop Practical"
        ),
        "SMALL_CIV": IntegrationCourse(
            "SMALL_CIV", 2, "CIVIL", 3, False, 1, "Surveying"
        ),
    }

    # Generate 50 students
    students: dict[str, IntegrationStudent] = {}
    for i in range(50):
        s_id = f"STU_{i:03d}"
        prog = "BTech-CSE" if i < 25 else "BTech-ECE"
        consent = i % 5 == 0  # 20% students have backlog consent
        students[s_id] = IntegrationStudent(s_id, prog, 1, consent)

    enrolments_by_course: dict[str, list[IntegrationEnrolment]] = {
        c: [] for c in courses
    }

    # Cohort 1: CSE101 and CSE102 (20 students)
    for i in range(20):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["CSE101"].append(
            IntegrationEnrolment(s_id, "CSE101")
        )
        enrolments_by_course["CSE102"].append(
            IntegrationEnrolment(s_id, "CSE102")
        )

    # Cohort 2: ECE101 and ECE102 (15 students)
    for i in range(20, 35):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["ECE101"].append(
            IntegrationEnrolment(s_id, "ECE101")
        )
        enrolments_by_course["ECE102"].append(
            IntegrationEnrolment(s_id, "ECE102")
        )

    # Cross-enrolled MEC101 (10 students)
    for i in range(35, 45):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["MEC101"].append(
            IntegrationEnrolment(s_id, "MEC101")
        )

    # CIV101 (10 students)
    for i in range(40, 50):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["CIV101"].append(
            IntegrationEnrolment(s_id, "CIV101")
        )

    # Supplementary exams (5 students each <= 50 -> AN only)
    for i in range(5):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["SUPP_CSE"].append(
            IntegrationEnrolment(s_id, "SUPP_CSE", is_backlog=True)
        )
    for i in range(20, 25):
        s_id = f"STU_{i:03d}"
        enrolments_by_course["SUPP_ECE"].append(
            IntegrationEnrolment(s_id, "SUPP_ECE", is_backlog=True)
        )

    # Small courses (6 students each)
    for i in range(6):
        s_id = f"STU_{10 + i:03d}"
        enrolments_by_course["SMALL_MEC"].append(
            IntegrationEnrolment(s_id, "SMALL_MEC")
        )
    for i in range(6):
        s_id = f"STU_{30 + i:03d}"
        enrolments_by_course["SMALL_CIV"].append(
            IntegrationEnrolment(s_id, "SMALL_CIV")
        )

    return IntegrationRegistry(
        courses=courses,
        students=students,
        sessions=sessions,
        halls=halls,
        enrolments_by_course=enrolments_by_course,
    )


def build_scenario_b_medium(seed: int = 101) -> IntegrationRegistry:
    """Build Scenario B: Medium examination problem.

    Scale:
      - 30 courses
      - 300 students
      - 10 examination dates (20 sessions, FN and AN)
      - Multiple cohorts across 4 departments (CSE, ECE, MECH, CIVIL)
      - Regular and backlog enrolments
      - Supplementary exams (both <= 50 and > 50)
      - Multiple hall configurations
    """
    rng = random.Random(seed)
    sessions = generate_session_sequence(
        date(2025, 12, 1), num_days=10, supp_window_days=3
    )

    halls = {
        "AUD_1": IntegrationHall("AUD_1", capacity=150),
        "AUD_2": IntegrationHall("AUD_2", capacity=120),
        "LAB_1": IntegrationHall("LAB_1", capacity=80),
    }

    depts = ["CSE", "ECE", "MECH", "CIVIL"]
    courses: dict[str, IntegrationCourse] = {}

    for i in range(30):
        dept = depts[i % 4]
        sem = (i % 6) + 1
        cr = 4 if i % 3 == 0 else 3
        is_supp = i >= 25
        code = f"{dept}_{sem:02d}_{i:02d}"
        courses[code] = IntegrationCourse(
            course_code=code,
            credits=cr,
            department=dept,
            duration_hours=3,
            is_supplementary=is_supp,
            semester=sem,
            name=f"{dept} Sem {sem} Course {i}",
        )

    students: dict[str, IntegrationStudent] = {}
    for i in range(300):
        s_id = f"STU_{i:04d}"
        dept = depts[i % 4]
        prog = f"BTech-{dept}"
        consent = i % 4 == 0
        students[s_id] = IntegrationStudent(s_id, prog, (i % 6) + 1, consent)

    enrolments_by_course: dict[str, list[IntegrationEnrolment]] = {
        c: [] for c in courses
    }

    # Populate course cohorts
    for code, c in courses.items():
        if c.is_supplementary:
            # 1 large supp (> 50 students) and 4 small supp (<= 50)
            count = 55 if code.endswith("25") else rng.randint(8, 25)
        else:
            count = rng.randint(20, 60)

        # Pick students from matching department
        matching = [
            s_id
            for s_id, s in students.items()
            if c.department in s.programme and s.semester == c.semester
        ]
        if len(matching) < count:
            matching = list(students.keys())

        chosen = rng.sample(matching, min(count, len(matching)))
        for s_id in chosen:
            enrolments_by_course[code].append(
                IntegrationEnrolment(s_id, code, is_backlog=c.is_supplementary)
            )

    return IntegrationRegistry(
        courses=courses,
        students=students,
        sessions=sessions,
        halls=halls,
        enrolments_by_course=enrolments_by_course,
    )


def build_scenario_c_large(seed: int = 777) -> IntegrationRegistry:
    """Build Scenario C: Large examination problem.

    Scale:
      - 100 courses
      - 1,000 students
      - 15 examination dates (30 sessions, FN and AN)
      - Realistic university cohort structure
    """
    rng = random.Random(seed)
    sessions = generate_session_sequence(
        date(2025, 12, 1), num_days=15, supp_window_days=3
    )

    halls = {
        "MAIN_AUD": IntegrationHall("MAIN_AUD", capacity=300),
        "HALL_A": IntegrationHall("HALL_A", capacity=200),
        "HALL_B": IntegrationHall("HALL_B", capacity=150),
        "HALL_C": IntegrationHall("HALL_C", capacity=150),
    }

    depts = ["CSE", "ECE", "MECH", "CIVIL", "AIML"]
    courses: dict[str, IntegrationCourse] = {}

    for i in range(100):
        dept = depts[i % 5]
        sem = (i % 8) + 1
        cr = 4 if i % 2 == 0 else 3
        is_supp = i >= 85
        code = f"{dept}{sem:02d}_{i:03d}"
        courses[code] = IntegrationCourse(
            course_code=code,
            credits=cr,
            department=dept,
            duration_hours=3,
            is_supplementary=is_supp,
            semester=sem,
            name=f"{dept} Course {i}",
        )

    students: dict[str, IntegrationStudent] = {}
    for i in range(1000):
        s_id = f"STU_{i:04d}"
        dept = depts[i % 5]
        prog = f"BTech-{dept}"
        consent = i % 3 == 0
        students[s_id] = IntegrationStudent(s_id, prog, (i % 8) + 1, consent)

    enrolments_by_course: dict[str, list[IntegrationEnrolment]] = {
        c: [] for c in courses
    }

    for code, c in courses.items():
        count = rng.randint(25, 80) if not c.is_supplementary else rng.randint(10, 45)
        matching = [
            s_id
            for s_id, s in students.items()
            if c.department in s.programme and s.semester == c.semester
        ]
        if len(matching) < count:
            matching = list(students.keys())
        chosen = rng.sample(matching, min(count, len(matching)))
        for s_id in chosen:
            enrolments_by_course[code].append(
                IntegrationEnrolment(s_id, code, is_backlog=c.is_supplementary)
            )

    return IntegrationRegistry(
        courses=courses,
        students=students,
        sessions=sessions,
        halls=halls,
        enrolments_by_course=enrolments_by_course,
    )


def build_scenario_d_infeasible() -> IntegrationRegistry:
    """Build Scenario D: Deliberately infeasible examination problem.

    Features:
      - Course with 120 students when max hall capacity is only 80 (capacity overflow)
      - Isolated small course (5 students, CSE) when zero other departments exist (no partner)
      - Two conflicting courses where only 1 session exists
    """
    sessions = (
        IntegrationExamSession(
            "2025-12-01_FN", 0, date(2025, 12, 1), SessionSlot.FN, False
        ),
    )

    hall = IntegrationHall("SMALL_HALL", capacity=80)  # cap_90 = 72

    c_overflow = IntegrationCourse(
        "OVERFLOW_100", 3, "CSE", 3, False, 1, "Massive Course"
    )
    c_small_isolated = IntegrationCourse(
        "ISOLATED_SMALL", 3, "CSE", 3, False, 1, "Lonely Course"
    )

    courses = {
        "OVERFLOW_100": c_overflow,
        "ISOLATED_SMALL": c_small_isolated,
    }

    students = {f"S_{i:03d}": IntegrationStudent(f"S_{i:03d}") for i in range(120)}

    enrolments_by_course = {
        "OVERFLOW_100": [
            IntegrationEnrolment(f"S_{i:03d}", "OVERFLOW_100")
            for i in range(100)
        ],
        "ISOLATED_SMALL": [
            IntegrationEnrolment(f"S_{i:03d}", "ISOLATED_SMALL")
            for i in range(5)
        ],
    }

    return IntegrationRegistry(
        courses=courses,
        students=students,
        sessions=sessions,
        halls={"SMALL_HALL": hall},
        enrolments_by_course=enrolments_by_course,
    )
