"""ALG-07: Supplementary Examination Eligibility.

Implements supplementary examination eligibility rules (BR-12, CN-28, EC-08, AS-015).

Public interface
----------------
is_supplementary_eligible(course, session, registry=None, *, enrolment_count=None)
    Determine whether a course can be scheduled into an examination session
    under the supplementary scheduling constraint (BR-12).

Constraints and specifications
------------------------------
BR-12   Supplementary Examinations:
        Supplementary backlog courses must be scheduled in AN sessions during
        the final three active days of the examination window. A backlog course
        with enrolment greater than fifty may use an FN session during those days.

CN-28   Hard Temporal Eligibility Constraint:
        If course.is_supplementary == True:
            date(c) in final 3 active examination dates
            AND (slot(c) == AN OR len(c.enrolments) > 50).
        This is a hard constraint that must never be relaxed.

EC-08   Final Day FN-Only:
        If the final active examination date contains only an FN session,
        supplementary courses with <= 50 students cannot use that FN session.
        Supplementary courses with > 50 students may use that FN session.

AS-015  Final Three Active Examination Dates:
        The supplementary window comprises the final 3 active examination dates
        (dates having at least one active session generated by ALG-02),
        as flagged by session.is_supplementary_window_date.

Complexity
----------
Time:   O(1) when enrolment counts are accessed via registry.enrolments_by_course
        or passed directly.
Space:  O(1) auxiliary space.

See docs/09_ALGORITHM_DESIGN.md §ALG-07, docs/04_BUSINESS_RULE_REGISTER.md §BR-12,
and docs/06_CONSTRAINT_CATALOGUE.md §CN-28.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from datetime import date
from typing import (
    Any,
    Protocol,
    runtime_checkable,
)

# Threshold above which supplementary courses unlock FN sessions (BR-12)
SUPPLEMENTARY_STUDENT_THRESHOLD: int = 50


# ---------------------------------------------------------------------------
# Structural Protocol classes (M1 compatibility layer)
# ---------------------------------------------------------------------------


@runtime_checkable
class CourseProtocol(Protocol):
    """Structural mirror of domain.Course (M1)."""

    course_code: str
    is_supplementary: bool


@runtime_checkable
class ExamSessionProtocol(Protocol):
    """Structural mirror of domain.ExamSession (M1)."""

    session_id: str
    exam_date: date
    slot: Any
    is_supplementary_window_date: bool


@runtime_checkable
class EnrolmentProtocol(Protocol):
    """Structural mirror of domain.Enrolment (M1)."""

    register_number: str
    course_code: str


@runtime_checkable
class ProblemRegistryProtocol(Protocol):
    """Structural mirror of domain.ProblemRegistry (M1)."""

    courses: Mapping[str, Any]
    enrolments_by_course: Mapping[str, Sequence[Any]]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _normalize_slot(slot: Any) -> str:
    """Normalize session slot to uppercase string ('FN' or 'AN')."""
    if hasattr(slot, "value"):
        return str(slot.value).upper()
    if hasattr(slot, "name"):
        return str(slot.name).upper()
    return str(slot).upper()


def get_course_enrolment_count(
    course_code: str,
    registry: Any | None = None,
    explicit_count: int | None = None,
) -> int:
    """Retrieve the total enrolment count for a course.

    Parameters
    ----------
    course_code:
        Unique identifier of the course.
    registry:
        Optional ProblemRegistry providing enrolments_by_course or enrolments_by_student.
    explicit_count:
        Optional precomputed enrolment count.

    Returns
    -------
    int
        Total enrolment count (regular + backlog).
    """
    if explicit_count is not None:
        return explicit_count
    if registry is None:
        return 0

    enrolments_by_course = getattr(registry, "enrolments_by_course", None)
    if enrolments_by_course is not None:
        enrols = enrolments_by_course.get(course_code)
        return len(enrols) if enrols is not None else 0

    enrolments_by_student = getattr(registry, "enrolments_by_student", None)
    if enrolments_by_student is not None:
        count = 0
        for enrol_list in enrolments_by_student.values():
            for enrol in enrol_list:
                if getattr(enrol, "course_code", None) == course_code:
                    count += 1
        return count

    return 0


# ---------------------------------------------------------------------------
# ALG-07 Public Function
# ---------------------------------------------------------------------------


def is_supplementary_eligible(
    course: CourseProtocol,
    session: ExamSessionProtocol,
    registry: ProblemRegistryProtocol | None = None,
    *,
    enrolment_count: int | None = None,
) -> bool:
    """Determine whether a course can be scheduled into an examination session (ALG-07).

    Enforces BR-12, CN-28, and EC-08:
    1. Regular courses (is_supplementary=False) are unconstrained by BR-12 -> True.
    2. Supplementary courses (is_supplementary=True):
       a. Must be in the final 3 active examination dates
          (session.is_supplementary_window_date == True).
       b. If enrolment_count <= 50: slot must be AN.
       c. If enrolment_count > 50: slot may be FN or AN.

    Parameters
    ----------
    course:
        The Course entity being evaluated.
    session:
        The candidate ExamSession entity.
    registry:
        Optional ProblemRegistry providing enrolment lookups.
    enrolment_count:
        Optional explicit integer enrolment count overriding registry lookup.

    Returns
    -------
    bool
        True if the placement satisfies supplementary eligibility rules;
        False otherwise.
    """
    # Rule 1: Regular courses are not constrained by supplementary rules (BR-12).
    if not getattr(course, "is_supplementary", False):
        return True

    # Rule 2: Supplementary courses are restricted to the supplementary window (AS-015).
    if not getattr(session, "is_supplementary_window_date", False):
        return False

    # Retrieve total enrolment count (Rule 6).
    count = get_course_enrolment_count(course.course_code, registry, enrolment_count)

    # Normalize slot string (FN or AN).
    slot_name = _normalize_slot(getattr(session, "slot", None))

    # Rule 4: Supplementary courses with more than 50 students can use FN or AN.
    if count > SUPPLEMENTARY_STUDENT_THRESHOLD:
        return slot_name in {"FN", "AN"}

    # Rule 3 & Rule 5: Courses with 50 or fewer students are restricted to AN only.
    # On an FN-only day (EC-08), this returns False since slot_name != "AN".
    return slot_name == "AN"
